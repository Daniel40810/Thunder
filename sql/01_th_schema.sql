SET DEFINE OFF

-- ---------------------------------------------------------------- Stufen
CREATE TABLE TH_STORM_LEVEL (
  LEVEL_ID     NUMBER(4)          CONSTRAINT TH_LEVEL_PK PRIMARY KEY,
  CODE         VARCHAR2(12)       NOT NULL CONSTRAINT TH_LEVEL_CODE_UK UNIQUE,
  NAME_DE      VARCHAR2(30 CHAR)  NOT NULL,
  SORT_ORDER   NUMBER(2)          NOT NULL CONSTRAINT TH_LEVEL_SORT_UK UNIQUE,
  RATE_SEC     NUMBER(4,2)        NOT NULL CONSTRAINT TH_LEVEL_RATE_CK  CHECK (RATE_SEC > 0),
  SHARE_IC     NUMBER(3,2)        NOT NULL CONSTRAINT TH_LEVEL_IC_CK    CHECK (SHARE_IC BETWEEN 0 AND 1),
  SHARE_CROWN  NUMBER(3,2)        NOT NULL CONSTRAINT TH_LEVEL_CROWN_CK CHECK (SHARE_CROWN BETWEEN 0 AND 1),
  DIST_MIN_KM  NUMBER(4,2)        NOT NULL,
  DIST_MAX_KM  NUMBER(4,2)        NOT NULL,
  RAIN_DROPS   NUMBER(5)          NOT NULL CONSTRAINT TH_LEVEL_RAIN_CK  CHECK (RAIN_DROPS >= 0),
  WIND         NUMBER(3,2)        NOT NULL CONSTRAINT TH_LEVEL_WIND_CK  CHECK (WIND BETWEEN 0 AND 2),
  EMBER        NUMBER(3,2)        NOT NULL CONSTRAINT TH_LEVEL_EMBER_CK CHECK (EMBER BETWEEN 0 AND 2),
  DESCRIPTION  VARCHAR2(200 CHAR),
  CONSTRAINT TH_LEVEL_SHARE_CK CHECK (SHARE_IC + SHARE_CROWN <= 1),
  CONSTRAINT TH_LEVEL_DIST_CK  CHECK (DIST_MIN_KM > 0 AND DIST_MIN_KM < DIST_MAX_KM)
);
COMMENT ON TABLE  TH_STORM_LEVEL             IS 'Wählbare Gewitterstufen der Thunder-App';
COMMENT ON COLUMN TH_STORM_LEVEL.RATE_SEC    IS 'mittlerer Abstand zwischen zwei Blitzen in Sekunden';
COMMENT ON COLUMN TH_STORM_LEVEL.SHARE_IC    IS 'Anteil Blitze in der Wolke (Wetterleuchten, Spinnenblitze)';
COMMENT ON COLUMN TH_STORM_LEVEL.SHARE_CROWN IS 'Anteil Blitzkronen aus dem Glutkern; Rest = Wolke-Erde';
COMMENT ON COLUMN TH_STORM_LEVEL.RAIN_DROPS  IS 'Anzahl gleichzeitig sichtbarer Regentropfen';
COMMENT ON COLUMN TH_STORM_LEVEL.WIND        IS 'Windstärke 0..2, wirkt auf Regen, Wolken, Strandhafer, Brandung';
COMMENT ON COLUMN TH_STORM_LEVEL.EMBER       IS 'Grundhelligkeit des orangen Glutkerns 0..2';

-- ---------------------------------------------------------------- Szenen
CREATE TABLE TH_SCENE (
  SCENE_ID     NUMBER(4)          CONSTRAINT TH_SCENE_PK PRIMARY KEY,
  CODE         VARCHAR2(20)       NOT NULL CONSTRAINT TH_SCENE_CODE_UK UNIQUE,
  NAME_DE      VARCHAR2(60 CHAR)  NOT NULL,
  HORIZON_Y    NUMBER(4,3)        NOT NULL CONSTRAINT TH_SCENE_HOR_CK   CHECK (HORIZON_Y BETWEEN 0.3 AND 0.8),
  SHORE_Y      NUMBER(4,3)        NOT NULL,
  EMBER_X      NUMBER(4,3)        NOT NULL CONSTRAINT TH_SCENE_EMBX_CK  CHECK (EMBER_X BETWEEN 0 AND 1),
  EMBER_Y      NUMBER(4,3)        NOT NULL,
  DESCRIPTION  VARCHAR2(200 CHAR),
  CONSTRAINT TH_SCENE_SHORE_CK CHECK (SHORE_Y > HORIZON_Y AND SHORE_Y < 1),
  CONSTRAINT TH_SCENE_EMBY_CK  CHECK (EMBER_Y > 0 AND EMBER_Y < HORIZON_Y)
);
COMMENT ON TABLE  TH_SCENE           IS 'Strandszenen; alle Positionen als Anteil der Bildhöhe/-breite (0..1)';
COMMENT ON COLUMN TH_SCENE.HORIZON_Y IS 'Horizontlinie (Meer beginnt)';
COMMENT ON COLUMN TH_SCENE.SHORE_Y   IS 'Uferlinie (Sand beginnt)';
COMMENT ON COLUMN TH_SCENE.EMBER_X   IS 'Lage des orange glühenden Wolkenkerns';

CREATE TABLE TH_SCENE_OBJECT (
  OBJ_ID       NUMBER(6)          CONSTRAINT TH_OBJ_PK PRIMARY KEY,
  SCENE_ID     NUMBER(4)          NOT NULL CONSTRAINT TH_OBJ_SCENE_FK REFERENCES TH_SCENE (SCENE_ID) ON DELETE CASCADE,
  OBJ_TYPE     VARCHAR2(12)       NOT NULL
                                  CONSTRAINT TH_OBJ_TYPE_CK CHECK (OBJ_TYPE IN ('STRANDKORB','LEUCHTTURM','SEEBRUECKE','DUENE')),
  POS_X        NUMBER(4,3)        NOT NULL CONSTRAINT TH_OBJ_X_CK     CHECK (POS_X BETWEEN 0 AND 1),
  DEPTH        NUMBER(4,3)        NOT NULL CONSTRAINT TH_OBJ_DEPTH_CK CHECK (DEPTH BETWEEN 0 AND 1),
  OBJ_SCALE    NUMBER(4,2)        DEFAULT 1 NOT NULL CONSTRAINT TH_OBJ_SCALE_CK CHECK (OBJ_SCALE > 0),
  COLOR_HEX    VARCHAR2(7)        CONSTRAINT TH_OBJ_COLOR_CK CHECK (REGEXP_LIKE(COLOR_HEX, '^#[0-9A-Fa-f]{6}$')),
  SORT_ORDER   NUMBER(3)          NOT NULL,
  CONSTRAINT TH_OBJ_SORT_UK UNIQUE (SCENE_ID, SORT_ORDER)
);
CREATE INDEX TH_OBJ_SCENE_IX ON TH_SCENE_OBJECT (SCENE_ID);
COMMENT ON TABLE  TH_SCENE_OBJECT           IS 'Objekte einer Strandszene';
COMMENT ON COLUMN TH_SCENE_OBJECT.DEPTH     IS 'Strand: 0 = Wasserkante, 1 = vorderer Bildrand; Leuchtturm/Seebrücke: 0 = am Horizont';
COMMENT ON COLUMN TH_SCENE_OBJECT.COLOR_HEX IS 'Streifenfarbe (Strandkorb) bzw. Bandfarbe (Leuchtturm), sichtbar im Blitzlicht';

-- ---------------------------------------------------------------- Farben
CREATE TABLE TH_PALETTE (
  PAL_ID       NUMBER(6)          CONSTRAINT TH_PAL_PK PRIMARY KEY,
  MOOD         VARCHAR2(5)        NOT NULL CONSTRAINT TH_PAL_MOOD_CK CHECK (MOOD IN ('ABEND','NACHT')),
  ROLE         VARCHAR2(20)       NOT NULL,
  COLOR_HEX    VARCHAR2(7)        NOT NULL CONSTRAINT TH_PAL_COLOR_CK CHECK (REGEXP_LIKE(COLOR_HEX, '^#[0-9A-Fa-f]{6}$')),
  CONSTRAINT TH_PAL_ROLE_UK UNIQUE (MOOD, ROLE)
);
COMMENT ON TABLE  TH_PALETTE      IS 'Farbstimmungen der Szene: Abendgewitter (mehr Orange) und Nacht';
COMMENT ON COLUMN TH_PALETTE.ROLE IS 'Farbrolle, z. B. SKY_TOP, EMBER, CLOUD_BASE, BOLT_GLOW';

-- ---------------------------------------------------------------- Blitzprotokoll
CREATE TABLE TH_STRIKE (
  STRIKE_ID    NUMBER(12)         CONSTRAINT TH_STRIKE_PK PRIMARY KEY,
  STRUCK_AT    TIMESTAMP(3)       DEFAULT SYSTIMESTAMP NOT NULL,
  LEVEL_ID     NUMBER(4)          CONSTRAINT TH_STRIKE_LEVEL_FK REFERENCES TH_STORM_LEVEL (LEVEL_ID) ON DELETE SET NULL,
  MOOD         VARCHAR2(5)        NOT NULL CONSTRAINT TH_STRIKE_MOOD_CK CHECK (MOOD IN ('ABEND','NACHT')),
  KIND         VARCHAR2(5)        NOT NULL CONSTRAINT TH_STRIKE_KIND_CK CHECK (KIND IN ('CG','IC','KRONE')),
  ORIGIN       VARCHAR2(5)        DEFAULT 'AUTO' NOT NULL CONSTRAINT TH_STRIKE_ORIGIN_CK CHECK (ORIGIN IN ('AUTO','KLICK')),
  DIST_KM      NUMBER(5,2)        NOT NULL CONSTRAINT TH_STRIKE_DIST_CK CHECK (DIST_KM > 0),
  PEAK_KA      NUMBER(4),
  POS_X        NUMBER(5,4)        NOT NULL,
  SEED         NUMBER(20)         NOT NULL,
  CONSTRAINT TH_STRIKE_KA_CK CHECK ((KIND = 'IC' AND PEAK_KA IS NULL) OR (KIND <> 'IC' AND PEAK_KA IS NOT NULL))
);
CREATE INDEX TH_STRIKE_AT_IX    ON TH_STRIKE (STRUCK_AT);
CREATE INDEX TH_STRIKE_LEVEL_IX ON TH_STRIKE (LEVEL_ID);
COMMENT ON TABLE  TH_STRIKE         IS 'Protokoll aller Blitze der App; mit SEED lässt sich die Blitzform wieder erzeugen';
COMMENT ON COLUMN TH_STRIKE.KIND    IS 'CG = Wolke-Erde, IC = in der Wolke, KRONE = Blitzkrone aus dem Glutkern';
COMMENT ON COLUMN TH_STRIKE.ORIGIN  IS 'AUTO = vom Gewitter erzeugt, KLICK = vom Benutzer ausgelöst';
COMMENT ON COLUMN TH_STRIKE.PEAK_KA IS 'Scheitelstromstärke in kA, negativ = negative Entladung; NULL bei IC';
COMMENT ON COLUMN TH_STRIKE.POS_X   IS 'Einschlagstelle (CG) bzw. Wolkenmitte (IC) als Anteil der Bildbreite';

-- ---------------------------------------------------------------- Sequenzen + Trigger (kein IDENTITY)
CREATE SEQUENCE TH_LEVEL_SEQ  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TH_SCENE_SEQ  START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TH_OBJ_SEQ    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TH_PAL_SEQ    START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE TH_STRIKE_SEQ START WITH 1 INCREMENT BY 1 CACHE 50;

CREATE OR REPLACE TRIGGER TH_LEVEL_BI BEFORE INSERT ON TH_STORM_LEVEL FOR EACH ROW
BEGIN
  IF :NEW.LEVEL_ID IS NULL THEN :NEW.LEVEL_ID := TH_LEVEL_SEQ.NEXTVAL; END IF;
END;
/
CREATE OR REPLACE TRIGGER TH_SCENE_BI BEFORE INSERT ON TH_SCENE FOR EACH ROW
BEGIN
  IF :NEW.SCENE_ID IS NULL THEN :NEW.SCENE_ID := TH_SCENE_SEQ.NEXTVAL; END IF;
END;
/
CREATE OR REPLACE TRIGGER TH_OBJ_BI BEFORE INSERT ON TH_SCENE_OBJECT FOR EACH ROW
BEGIN
  IF :NEW.OBJ_ID IS NULL THEN :NEW.OBJ_ID := TH_OBJ_SEQ.NEXTVAL; END IF;
END;
/
CREATE OR REPLACE TRIGGER TH_PAL_BI BEFORE INSERT ON TH_PALETTE FOR EACH ROW
BEGIN
  IF :NEW.PAL_ID IS NULL THEN :NEW.PAL_ID := TH_PAL_SEQ.NEXTVAL; END IF;
END;
/
CREATE OR REPLACE TRIGGER TH_STRIKE_BI BEFORE INSERT ON TH_STRIKE FOR EACH ROW
BEGIN
  IF :NEW.STRIKE_ID IS NULL THEN :NEW.STRIKE_ID := TH_STRIKE_SEQ.NEXTVAL; END IF;
END;
/

-- ---------------------------------------------------------------- Auswertung
CREATE OR REPLACE VIEW TH_STRIKE_DAY_V AS
SELECT TRUNC(s.STRUCK_AT)                                   AS TAG,
       NVL(l.NAME_DE, '–')                                  AS STUFE,
       COUNT(*)                                             AS BLITZE,
       SUM(CASE WHEN s.KIND = 'CG'    THEN 1 ELSE 0 END)    AS WOLKE_ERDE,
       SUM(CASE WHEN s.KIND = 'IC'    THEN 1 ELSE 0 END)    AS IN_DER_WOLKE,
       SUM(CASE WHEN s.KIND = 'KRONE' THEN 1 ELSE 0 END)    AS KRONEN,
       SUM(CASE WHEN s.ORIGIN = 'KLICK' THEN 1 ELSE 0 END)  AS GEKLICKT,
       ROUND(MIN(s.DIST_KM), 2)                             AS NAECHSTER_KM,
       ROUND(AVG(s.DIST_KM), 2)                             AS MITTEL_KM,
       MIN(s.PEAK_KA)                                       AS STAERKSTER_KA
  FROM TH_STRIKE s
  LEFT JOIN TH_STORM_LEVEL l ON l.LEVEL_ID = s.LEVEL_ID
 GROUP BY TRUNC(s.STRUCK_AT), NVL(l.NAME_DE, '–');
COMMENT ON TABLE TH_STRIKE_DAY_V IS 'Blitze je Tag und Stufe; STAERKSTER_KA = betragsmäßig stärkste negative Entladung';
